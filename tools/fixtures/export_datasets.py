"""Exports the tiny classic datasets bundled with the app as TypeScript modules.

Run from the repository root:  python tools/fixtures/export_datasets.py
They come from scikit-learn (which redistributes them); see docs/DATASETS.md for sources and licences.
"""
import json
import pathlib

from sklearn import datasets

OUT = pathlib.Path(__file__).resolve().parents[2] / 'packages' / 'core' / 'src' / 'datasets'
OUT.mkdir(parents=True, exist_ok=True)

SPECS = [
    ('iris', datasets.load_iris(), 'Iris flowers (Fisher, 1936)', 'UCI Machine Learning Repository; public domain'),
    ('wine', datasets.load_wine(), 'Chemical analysis of Italian wines', 'UCI Machine Learning Repository; CC BY 4.0'),
    ('diabetes', datasets.load_diabetes(), 'Diabetes progression after one year (Efron et al., 2004)', 'scikit-learn (BSD-3-Clause)'),
    ('breastCancer', datasets.load_breast_cancer(), 'Breast Cancer Wisconsin (diagnostic)', 'UCI Machine Learning Repository; CC BY 4.0'),
]

index = []
for key, ds, title, licence in SPECS:
    classification = hasattr(ds, 'target_names') and len(getattr(ds, 'target_names', [])) > 0
    payload = {
        'id': key,
        'title': title,
        'licence': licence,
        'kind': 'classification' if classification else 'regression',
        'features': [str(f) for f in ds.feature_names],
        'classes': [str(c) for c in ds.target_names] if classification else None,
        'rows': [[round(float(v), 4) for v in row] for row in ds.data],
        'target': [int(t) for t in ds.target] if classification else [round(float(t), 2) for t in ds.target],
    }
    text = (
        "// Generated by tools/fixtures/export_datasets.py: do not edit by hand.\n"
        f"import type {{ ClassicDataset }} from './types';\n\nexport const {key}: ClassicDataset = "
        + json.dumps(payload, separators=(',', ':'))
        + ';\n'
    )
    (OUT / f'{key}.ts').write_text(text, encoding='utf8')
    index.append(key)
    print(key, len(payload['rows']), 'rows', (OUT / f'{key}.ts').stat().st_size, 'bytes')

(OUT / 'types.ts').write_text(
    """export interface ClassicDataset {
  id: string;
  title: string;
  licence: string;
  kind: 'classification' | 'regression';
  features: string[];
  classes: string[] | null;
  rows: number[][];
  target: number[];
}
""",
    encoding='utf8',
)
(OUT / 'index.ts').write_text(
    "export type { ClassicDataset } from './types';\n"
    + ''.join(f"export {{ {k} }} from './{k}';\n" for k in index)
    + "\nimport { breastCancer } from './breastCancer';\nimport { diabetes } from './diabetes';\nimport { iris } from './iris';\nimport { wine } from './wine';\n"
    + "\nexport const CLASSIC_DATASETS = { iris, wine, diabetes, breastCancer } as const;\nexport type ClassicDatasetId = keyof typeof CLASSIC_DATASETS;\n",
    encoding='utf8',
)
